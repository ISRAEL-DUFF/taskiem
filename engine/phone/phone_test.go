// The table the web (web/src/lib/phone.ts) and the app read numbers by too.
var table = []struct{ in, want string }{
	{"08031234567", "+2348031234567"},
	{"0803 123 4567", "+2348031234567"},
	{"0803-123-4567", "+2348031234567"},
	{"(0803) 123.4567", "+2348031234567"},
	{"8031234567", "+2348031234567"},
	{"7031234567", "+2347031234567"},
	{"9031234567", "+2349031234567"},
	{"+2348031234567", "+2348031234567"},
	{"+234 803 123 4567", "+2348031234567"},
	{"+23408031234567", "+2348031234567"},
	{"+234 0803 123 4567", "+2348031234567"},
	{"002348031234567", "+2348031234567"},
	{"0023408031234567", "+2348031234567"},
	{"+447911123456", "+447911123456"},
	{"00447911123456", "+447911123456"},
	{"+1 (415) 555-0100", "+14155550100"},
	{"+12345678", "+12345678"},
	{"+123456789012345", "+123456789012345"},
	{"", ""},
	{"hello", ""},
	{"2348031234567", ""},
	{"6031234567", ""},
	{"803123456", ""},
	{"080312345678", ""},
	{"+2346031234567", ""},
	{"+234803123456", ""},
	{"+23480312345678", ""},
	{"+1234567", ""},
	{"+1234567890123456", ""},
	{"+0441234567", ""},
	{"+44 7911 12345a", ""},
	{"++2348031234567", ""},
}

func TestNormalise(t *testing.T) {
	for _, c := range table {
		got, err := Normalise(c.in)
		if c.want == "" {
			if err == nil {
				t.Errorf("Normalise(%q) = %q, want invalid", c.in, got)
			}
			continue
		}
		if err != nil || got != c.want {
			t.Errorf("Normalise(%q) = %q, %v; want %q", c.in, got, err, c.want)
		}
	}
}
