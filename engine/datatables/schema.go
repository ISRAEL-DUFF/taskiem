// Schema changes go through Xenibase's structured schema API with the
// connection's own token: a preview, then an apply with the preview's
// hash, so what runs is what Xenibase showed, and Taskiem never writes
// SQL text (decision 0033). Drops carry the typed confirmation the API
// collected from the person.

// Change is one schema change as Xenibase takes it (SchemaChange).
type Change struct {
	Kind    string         // create_table, add_column, drop_column, drop_table
	Table   string         // in public
	Columns []Column       // create_table
	Column  *Column        // add_column
	Name    string         // drop_column: the column
	Confirm string         // drops: the object's name, typed
	body    map[string]any // as sent
}

// CreateTableChange makes every table alike: id bigint generated by
// default as identity primary key, created_at and updated_at timestamptz
// not null default now(), then the declared columns (required: not
// null). The identity is by default rather than always so an export can
// be imported back on id.
func CreateTableChange(name string, cols []Column) Change {
	defs := []any{
		map[string]any{"name": "id", "type": "bigint generated by default as identity", "nullable": false, "primary_key": true},
		map[string]any{"name": "created_at", "type": "timestamptz", "nullable": false, "default": "now()"},
		map[string]any{"name": "updated_at", "type": "timestamptz", "nullable": false, "default": "now()"},
	}
	for _, c := range cols {
		defs = append(defs, columnDef(c))
	}
	return Change{Kind: "create_table", Table: name, Columns: cols, body: map[string]any{"kind": "create_table", "schema": "public", "table": name, "columns": defs}}
}

// AddColumnChange adds a column; a required one with rows already there
// is refused by Postgres, which the API explains.
func AddColumnChange(table string, c Column) Change {
	return Change{Kind: "add_column", Table: table, Column: &c, body: map[string]any{"kind": "add_column", "schema": "public", "table": table, "column": columnDef(c)}}
}

// DropColumnChange drops a column and its data.
func DropColumnChange(table, column, confirm string) Change {
	return Change{Kind: "drop_column", Table: table, Name: column, Confirm: confirm, body: map[string]any{"kind": "drop_column", "schema": "public", "table": table, "column_name": column}}
}

// DropTableChange drops a table and every row.
func DropTableChange(table, confirm string) Change {
	return Change{Kind: "drop_table", Table: table, Confirm: confirm, body: map[string]any{"kind": "drop_table", "schema": "public", "table": table}}
}

func columnDef(c Column) map[string]any {
	d := map[string]any{"name": c.Name, "type": PGType(c.Type), "nullable": !c.Required}
	if c.Title != "" {
		d["comment"] = c.Title
	}
	return d
}

// Body is the change as sent to Xenibase (for tests and messages).
func (c Change) Body() map[string]any { return c.body }

// Apply previews and applies a change in the organisation's project with
// the data_tables connection's token, recording the credential read
// under purpose. A drop needs the object's name typed as Confirm; the
// preview says what Xenibase wants confirmed and the apply is refused
// before it is sent when they differ.
func (s *Service) Apply(ctx context.Context, tenant uuid.UUID, actor string, change Change) error {
	if change.body == nil {
		return fmt.Errorf("%w: an empty change", ErrInvalid)
	}
	creds, err := s.Credentials(secrets.WithUse(ctx, secrets.Use{Kind: secrets.KindConnection, Purpose: "tables.schema", Actor: actor}), tenant)
	if err != nil {
		return err
	}
	base := strings.TrimSpace(creds["base_url"])
	if base == "" {
		base = s.ConnectorURL
	}
	if base == "" {
		base = s.Platform.URL
	}
	c, err := s.newClient(tenant.String(), base, creds["token"], "xenibase:schema")
	if err != nil {
		return err
	}
	project := strings.TrimSpace(creds["project_id"])
	if project == "" {
		return fmt.Errorf("%w: the %s connection names no project", ErrInvalid, ConnectionName)
	}
	p, err := c.previewSchema(ctx, project, change.body)
	if err != nil {
		return err
	}
	if p.Confirm != "" && change.Confirm != p.Confirm {
		return fmt.Errorf("%w: type %q to confirm dropping it", ErrInvalid, p.Confirm)
	}
	if p.Hash == "" {
		return fmt.Errorf("%w: the preview carries no hash", ErrProjectFailed)
	}
	confirm := ""
	if p.Confirm != "" {
		confirm = change.Confirm
	}
	return c.applySchema(ctx, project, change.body, p.Hash, confirm)
}

func marshal(v map[string]any) ([]byte, error) {
	if v == nil {
		v = map[string]any{}
	}
	return json.Marshal(v)
}
