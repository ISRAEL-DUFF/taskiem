// Command sdkgen writes sdk/src/connectors.gen.ts: typed step helpers for
// the connectors built into the binary, so flow code reads
// iswallet.transfer({...}) and editors check the inputs. Run it with
// `go generate ./sdk` after changing a manifest; a test fails if the file
// is stale.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/israel-duff/taskiem/connectors/builtin"
	"github.com/israel-duff/taskiem/engine/capability"
	"github.com/israel-duff/taskiem/engine/connector"
	"github.com/israel-duff/taskiem/engine/wd"
)

func main() {
	out := "src/connectors.gen.ts"
	if len(os.Args) > 1 {
		out = os.Args[1]
	}
	src, err := Generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, "sdkgen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil { //nolint:gosec // a source file
		fmt.Fprintln(os.Stderr, "sdkgen:", err)
		os.Exit(1)
	}
}

var nonIdent = regexp.MustCompile(`[^A-Za-z0-9_]`)

// Generate renders the helpers module.
func Generate() ([]byte, error) {
	reg := connector.NewRegistry()
	if err := builtin.Register(reg, builtin.Options{}); err != nil {
		return nil, err
	}
	conns := reg.List()
	sort.Slice(conns, func(i, j int) bool { return conns[i].Ref() < conns[j].Ref() })
	var b bytes.Buffer
	b.WriteString("// Generated by tools/sdkgen from the connector manifests built into taskiem.\n// Do not edit: run `go generate ./sdk` instead.\n\n")
	b.WriteString("import { capability, connector, type CapabilityExtra, type ConnectorExtra, type StepSpec, type Val, type Value } from \"./builder.js\";\n")
	helpers := map[string]string{}
	actionsOf := map[string][]string{}
	for _, c := range conns {
		ref := c.Ref()
		name := nonIdent.ReplaceAllString(c.Manifest.ID, "_")
		if major := strings.TrimPrefix(ref, c.Manifest.ID+"@"); major != "1" {
			name += "_v" + major
		}
		helpers[ref] = name
		fmt.Fprintf(&b, "\n// %s (%s)\n", c.Manifest.Name, ref)
		actions := make([]string, 0, len(c.Manifest.Actions))
		for a := range c.Manifest.Actions {
			actions = append(actions, a)
		}
		sort.Strings(actions)
		actionsOf[ref] = actions
		type entry struct {
			action, iface, doc string
			optional           bool
		}
		var entries []entry
		for _, a := range actions {
			spec := c.Manifest.Actions[a]
			iface := typeName(name) + typeName(a) + "Input"
			fields, optional, err := inputFields(spec.Input)
			if err != nil {
				return nil, fmt.Errorf("%s %s: %w", ref, a, err)
			}
			fmt.Fprintf(&b, "export interface %s {\n%s}\n", iface, fields)
			doc := spec.Title
			if doc == "" {
				doc = a
			}
			entries = append(entries, entry{a, iface, fmt.Sprintf("%s (%s)", doc, spec.Class), optional})
		}
		fmt.Fprintf(&b, "export const %s = {\n", name)
		for _, e := range entries {
			q := ""
			if e.optional {
				q = "?"
			}
			fmt.Fprintf(&b, "  /** %s */\n  %s: (input%s: %s, extra?: ConnectorExtra): StepSpec => connector(%q, %q, input, extra),\n",
				strings.ReplaceAll(e.doc, "*/", "* /"), e.action, q, e.iface, ref, e.action)
		}
		b.WriteString("};\n")
	}
	refs := make([]string, 0, len(helpers))
	for r := range helpers {
		refs = append(refs, r)
	}
	sort.Strings(refs)
	b.WriteString("\n/** Connector refs with helpers here, for code generation. */\nexport const CONNECTOR_HELPERS: Record<string, string> = {\n")
	for _, r := range refs {
		fmt.Fprintf(&b, "  %q: %q,\n", r, helpers[r])
	}
	b.WriteString("};\n")
	b.WriteString("\n/** The actions each helper has: any other action is generated as connector(...). */\nexport const CONNECTOR_ACTIONS: Record<string, readonly string[]> = {\n")
	for _, r := range refs {
		q := make([]string, len(actionsOf[r]))
		for i, a := range actionsOf[r] {
			q[i] = strconv.Quote(a)
		}
		fmt.Fprintf(&b, "  %q: [%s],\n", r, strings.Join(q, ", "))
	}
	b.WriteString("};\n")
	if err := capabilities(&b, conns); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// capabilities renders the capability set's input and output types
// (schemas/capabilities-v1.json) and which built-in rails declare each.
func capabilities(b *bytes.Buffer, conns []*connector.Connector) error {
	b.WriteString("\n// Capabilities (schemas/capabilities-v1.json): the same input and output on every rail.\n")
	railsOf := map[string][]string{}
	for _, c := range conns {
		for n := range c.Manifest.Capabilities {
			railsOf[n] = append(railsOf[n], c.Ref())
		}
	}
	for _, n := range capability.Names() {
		spec, _ := capability.Get(n)
		in, _, err := inputFields(spec.Input)
		if err != nil {
			return fmt.Errorf("capability %s: %w", n, err)
		}
		fmt.Fprintf(b, "/** %s: input */\nexport interface Capability%sInput {\n%s}\n", spec.Title, typeName(n), in)
		var out map[string]any
		if err := json.Unmarshal(spec.Output, &out); err != nil {
			return fmt.Errorf("capability %s: %w", n, err)
		}
		fmt.Fprintf(b, "/** %s: output */\nexport type Capability%sOutput = %s;\n", spec.Title, typeName(n), outType(out, ""))
	}
	b.WriteString("/** await_settlement and await_reversal: input */\nexport interface CapabilityAwaitInput {\n  /** The payout to follow: the payment step's output.payout_id */\n  payout_id: Val<string>;\n}\n")
	b.WriteString("/** await_payment: input */\nexport interface CapabilityAwaitPaymentInput {\n  /** The payment page to wait on: the collect_link step's output.payment_id */\n  payment_id: Val<string>;\n}\n")
	groups := map[string][][2]string{} // helper object -> (key, uses)
	helperOf := map[string]string{}
	for _, n := range append(capability.Names(), wd.Waits...) {
		g, key := helperGroup(n)
		groups[g] = append(groups[g], [2]string{key, n})
		helperOf[n] = g + "." + key
	}
	gnames := make([]string, 0, len(groups))
	for g := range groups {
		gnames = append(gnames, g)
	}
	sort.Strings(gnames)
	for _, g := range gnames {
		fmt.Fprintf(b, "/** Capability steps (%s): each runs on whichever rail its connection is. */\nexport const %s = {\n", g, g)
		for _, e := range groups[g] {
			iface, title := "Capability"+typeName(e[1])+"Input", ""
			if spec, ok := capability.Get(e[1]); ok {
				title = spec.Title
			} else {
				iface, title = "CapabilityAwaitInput", capability.WaitTitle(e[1])
				if e[1] == "await_payment" {
					iface = "CapabilityAwaitPaymentInput"
				}
			}
			fmt.Fprintf(b, "  /** %s */\n  %s: (input: %s, extra?: CapabilityExtra): StepSpec => capability(%q, input, extra),\n", title, e[0], iface, e[1])
		}
		b.WriteString("};\n")
	}
	b.WriteString("\n/** The helper each capability has, for code generation. */\nexport const CAPABILITY_HELPERS: Record<string, string> = {\n")
	hnames := make([]string, 0, len(helperOf))
	for n := range helperOf {
		hnames = append(hnames, n)
	}
	sort.Strings(hnames)
	for _, n := range hnames {
		fmt.Fprintf(b, "  %s: %q,\n", n, helperOf[n])
	}
	b.WriteString("};\n")
	b.WriteString("\n/** The built-in rails that declare each capability. */\nexport const CAPABILITY_RAILS: Record<string, readonly string[]> = {\n")
	for _, n := range capability.Names() {
		rails := railsOf[n]
		sort.Strings(rails)
		q := make([]string, len(rails))
		for i, r := range rails {
			q[i] = strconv.Quote(r)
		}
		fmt.Fprintf(b, "  %s: [%s],\n", n, strings.Join(q, ", "))
	}
	b.WriteString("};\n")
	return nil
}

// outType is a schema as a plain TypeScript type: what a step's output holds.
func outType(p map[string]any, indent string) string {
	if enum, ok := p["enum"].([]any); ok && len(enum) > 0 {
		parts := make([]string, len(enum))
		for i, e := range enum {
			j, _ := json.Marshal(e)
			parts[i] = string(j)
		}
		return strings.Join(parts, " | ")
	}
	switch p["type"] {
	case "string":
		return "string"
	case "integer", "number":
		return "number"
	case "boolean":
		return "boolean"
	case "array":
		if items, ok := p["items"].(map[string]any); ok {
			return "Array<" + outType(items, indent) + ">"
		}
		return "unknown[]"
	}
	props, _ := p["properties"].(map[string]any)
	if props == nil {
		return "Record<string, unknown>"
	}
	req := map[string]bool{}
	if r, ok := p["required"].([]any); ok {
		for _, x := range r {
			req[fmt.Sprint(x)] = true
		}
	}
	names := make([]string, 0, len(props))
	for n := range props {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("{\n")
	for _, n := range names {
		sub, _ := props[n].(map[string]any)
		opt := "?"
		if req[n] {
			opt = ""
		}
		fmt.Fprintf(&b, "%s  %s%s: %s;\n", indent, n, opt, outType(sub, indent+"  "))
	}
	b.WriteString(indent + "}")
	return b.String()
}

func typeName(s string) string {
	var out strings.Builder
	for _, p := range strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' }) {
		out.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return out.String()
}

// inputFields renders an action's input schema's properties as interface
// fields; optional reports whether the whole input may be omitted.
func inputFields(raw json.RawMessage) (string, bool, error) {
	if len(raw) == 0 {
		return "  [key: string]: Value;\n", true, nil
	}
	var s struct {
		Properties map[string]map[string]any `json:"properties"`
		Required   []string                  `json:"required"`
	}
	if err := json.Unmarshal(raw, &s); err != nil {
		return "", false, err
	}
	req := map[string]bool{}
	for _, r := range s.Required {
		req[r] = true
	}
	names := make([]string, 0, len(s.Properties))
	for n := range s.Properties {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	for _, n := range names {
		p := s.Properties[n]
		if d, ok := p["description"].(string); ok && d != "" {
			fmt.Fprintf(&b, "  /** %s */\n", strings.ReplaceAll(d, "*/", "* /"))
		}
		opt := "?"
		if req[n] {
			opt = ""
		}
		key := n
		if nonIdent.MatchString(n) {
			key = fmt.Sprintf("%q", n)
		}
		fmt.Fprintf(&b, "  %s%s: %s;\n", key, opt, tsType(p))
	}
	if len(names) == 0 {
		b.WriteString("  [key: string]: Value;\n")
	}
	return b.String(), len(s.Required) == 0, nil
}

func tsType(p map[string]any) string {
	if enum, ok := p["enum"].([]any); ok && len(enum) > 0 {
		parts := make([]string, len(enum))
		for i, e := range enum {
			j, _ := json.Marshal(e)
			parts[i] = string(j)
		}
		return "Val<" + strings.Join(parts, " | ") + ">"
	}
	switch p["type"] {
	case "string":
		return "Val<string>"
	case "integer", "number":
		return "Val<number>"
	case "boolean":
		return "Val<boolean>"
	}
	return "Value" // objects and lists: literals or expressions at any depth
}

// helperGroup is where a capability's helper lives: pay.bank, collect.link,
// waitFor.settlement, and rail.<name> for the rest.
func helperGroup(uses string) (group, key string) {
	for _, g := range []struct{ prefix, group string }{{"pay_", "pay"}, {"collect_", "collect"}, {"await_", "waitFor"}} {
		if k, ok := strings.CutPrefix(uses, g.prefix); ok {
			return g.group, k
		}
	}
	return "rail", uses
}
