package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// The web's icons (web/src/icons.tsx): each a path on a 24-unit grid, drawn
// with a 1.7 stroke in the colour around it; and Taskiem's mark in the chat,
// two filled sparks. The app draws the same paths (lib/kit/icon.dart).

const (
	// IconsFrom is the web's icons, from the repository root.
	IconsFrom = "web/src/icons.tsx"
	// IconsOut is the app's copy.
	IconsOut = "mobile/lib/theme/icons.g.dart"
)

var (
	iconEntry = regexp.MustCompile(`(?m)^\s+"?([a-z][a-z0-9-]*)"?:\s*"([^"]+)",`)
	markPath  = regexp.MustCompile(`<path d="([^"]+)" />`)
)

// GenerateIcons answers the Dart file of the web's icon paths.
func GenerateIcons(root string) (string, error) {
	raw, err := os.ReadFile(filepath.Join(root, IconsFrom))
	if err != nil {
		return "", err
	}
	src := string(raw)
	start := strings.Index(src, "const paths")
	end := strings.Index(src, "\n};")
	if start < 0 || end < start {
		return "", fmt.Errorf("%s: no `const paths = {...}`", IconsFrom)
	}
	entries := iconEntry.FindAllStringSubmatch(src[start:end], -1)
	if len(entries) == 0 {
		return "", fmt.Errorf("%s: no icons read", IconsFrom)
	}
	mark := strings.Index(src, "export function TaskiemMark")
	if mark < 0 {
		return "", fmt.Errorf("%s: no TaskiemMark", IconsFrom)
	}
	sparks := markPath.FindAllStringSubmatch(src[mark:], -1)
	if len(sparks) == 0 {
		return "", fmt.Errorf("%s: TaskiemMark has no paths", IconsFrom)
	}
	var b strings.Builder
	b.WriteString(`// GENERATED by tools/mobilegen from web/src/icons.tsx: the web's icons, each
// a path on a 24-unit grid drawn with a 1.7 stroke (docs/spec/mobile-app.md
// §4.1). Do not edit; change the web's icons and run ` + "`go run ./tools/mobilegen`" + `.

/// The web's line icons by name.
const tkIconPaths = <String, String>{
`)
	for _, e := range entries {
		fmt.Fprintf(&b, "  '%s': '%s',\n", e[1], e[2])
	}
	b.WriteString("};\n\n/// Taskiem's mark in the chat: filled sparks, in the colour around them.\nconst tkTaskiemMarkPaths = <String>[\n")
	for _, p := range sparks {
		fmt.Fprintf(&b, "  '%s',\n", p[1])
	}
	b.WriteString("];\n")
	return b.String(), nil
}
