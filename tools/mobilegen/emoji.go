package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// The emoji panel's characters (web/src/lib/emojiData.ts, itself generated
// from Unicode's data by web/scripts/gen-emoji.mjs), copied so the app's
// panel holds the web's emoji in the web's groups, named and found by the
// same words (lib/chat/emoji.dart reads them).

const (
	// EmojiFrom is the web's emoji list, from the repository root.
	EmojiFrom = "web/src/lib/emojiData.ts"
	// EmojiOut is the app's copy.
	EmojiOut = "mobile/lib/chat/emoji.g.dart"
)

var (
	emojiGroup    = regexp.MustCompile("(?s)\\[\\s*\"([a-z]+)\",\\s*\"([^\"]+)\",\\s*\"([^\"]+)\",\\s*`([^`]*)`,?\\s*\\]")
	emojiToneable = regexp.MustCompile("TONEABLE_SOURCE = `([^`]*)`")
)

// GenerateEmoji answers the Dart file of the web's emoji list.
func GenerateEmoji(root string) (string, error) {
	raw, err := os.ReadFile(filepath.Join(root, EmojiFrom))
	if err != nil {
		return "", err
	}
	src := string(raw)
	groups := emojiGroup.FindAllStringSubmatch(src, -1)
	if len(groups) == 0 {
		return "", fmt.Errorf("%s: no groups", EmojiFrom)
	}
	tone := emojiToneable.FindStringSubmatch(src)
	if tone == nil {
		return "", fmt.Errorf("%s: no TONEABLE_SOURCE", EmojiFrom)
	}
	var b strings.Builder
	b.WriteString(`// GENERATED by tools/mobilegen from web/src/lib/emojiData.ts (itself from
// Unicode's emoji-test.txt and CLDR's English annotations, Unicode 14 and
// older). Do not edit; run ` + "`go run ./tools/mobilegen`" + `.
// Unicode data files and software: Copyright © 1991-2025 Unicode, Inc.,
// under the Unicode License v3 (https://www.unicode.org/license.txt).

/// One group: its id, its name, its icon, and its emoji a line:
/// "😀 grinning face|words that find it".
const emojiSource = <(String, String, String, String)>[
`)
	for _, g := range groups {
		if strings.Contains(g[4], "'''") {
			return "", fmt.Errorf("%s: group %s holds '''", EmojiFrom, g[1])
		}
		fmt.Fprintf(&b, "  (\n    '%s',\n    '%s',\n    '%s',\n    r'''%s''',\n  ),\n", g[1], strings.ReplaceAll(g[2], "'", "\\'"), g[3], g[4])
	}
	b.WriteString("];\n\n/// The emoji that take a skin tone, a space between each.\n")
	fmt.Fprintf(&b, "const toneableSource = '%s';\n", tone[1])
	return b.String(), nil
}
