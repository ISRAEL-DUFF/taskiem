package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// The chat's words that are data on the web (web/src/lib/linkchat.ts): how a
// card's event is said ("sent invoice"), copied so the app's previews say
// what the web's say (lib/chat/words.dart uses them).

const (
	// WordsFrom is the web's chat words, from the repository root.
	WordsFrom = "web/src/lib/linkchat.ts"
	// WordsOut is the app's copy.
	WordsOut = "mobile/lib/chat/words.g.dart"
)

var wordEntry = regexp.MustCompile(`(?m)^\s+"?([a-z_]+)"?:\s*"([^"]*)",`)

// GenerateWords answers the Dart file of the web's chat word tables.
func GenerateWords(root string) (string, error) {
	raw, err := os.ReadFile(filepath.Join(root, WordsFrom))
	if err != nil {
		return "", err
	}
	src := string(raw)
	var b strings.Builder
	b.WriteString(`// GENERATED by tools/mobilegen from web/src/lib/linkchat.ts: the words a
// card's event is said in, as the web says them. Do not edit; change the
// web's and run ` + "`go run ./tools/mobilegen`" + `.
`)
	for _, t := range []struct{ ts, dart, doc string }{
		{"VERB", "cardVerbs", "An order's or an invoice's event, said after who did it."},
		{"DELIVERY_VERB", "deliveryVerbs", "A delivery's event, from either side."},
	} {
		start := strings.Index(src, "const "+t.ts+": Record<string, string> = {")
		if start < 0 {
			return "", fmt.Errorf("%s: no %s", WordsFrom, t.ts)
		}
		end := strings.Index(src[start:], "\n};")
		if end < 0 {
			return "", fmt.Errorf("%s: %s does not end", WordsFrom, t.ts)
		}
		entries := wordEntry.FindAllStringSubmatch(src[start:start+end], -1)
		if len(entries) == 0 {
			return "", fmt.Errorf("%s: %s has no words", WordsFrom, t.ts)
		}
		fmt.Fprintf(&b, "\n/// %s\nconst %s = <String, String>{\n", t.doc, t.dart)
		for _, e := range entries {
			fmt.Fprintf(&b, "  '%s': '%s',\n", e[1], strings.ReplaceAll(e[2], "'", "\\'"))
		}
		b.WriteString("};\n")
	}
	return b.String(), nil
}
